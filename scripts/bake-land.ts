// One-off: turns Natural Earth's 110 m land (public domain, via the world-atlas TopoJSON) into the small bit mask the
// entry sequence draws as a dot-matrix globe. Not part of `pnpm build`; the output is committed.
//   node scripts/bake-land.ts <path to land-110m.json>      (writes src/lib/land-mask.ts)
// The mask is a 2° grid: 90 rows (lat 89 down to -89) × 180 columns (lon -179 to 179), one bit per cell, row-major,
// base64. A cell is land when its centre is inside a land polygon.
import { readFileSync, writeFileSync } from 'node:fs';

type Pt = [number, number];
interface Topology {
  transform: { scale: [number, number]; translate: [number, number] };
  arcs: [number, number][][];
  objects: { land: { geometries: { type: string; arcs: number[][][] | number[][] }[] } };
}

const input = process.argv[2];
if (!input) throw new Error('usage: node scripts/bake-land.ts <land-110m.json>');
const topo = JSON.parse(readFileSync(input, 'utf8')) as Topology;
const { scale, translate } = topo.transform;

const arcs: Pt[][] = topo.arcs.map((arc) => {
  let x = 0;
  let y = 0;
  return arc.map(([dx, dy]) => {
    x += dx;
    y += dy;
    return [x * scale[0] + translate[0], y * scale[1] + translate[1]] as Pt;
  });
});

/** A ring from arc indices; a negative index (~i) walks that arc backwards. Joint points are not repeated. */
function ring(indices: number[]): Pt[] {
  const out: Pt[] = [];
  for (const i of indices) {
    const pts = i >= 0 ? arcs[i] : arcs[~i]?.toReversed();
    if (!pts) continue;
    out.push(...(out.length ? pts.slice(1) : pts));
  }
  return out;
}

const inRing = (lon: number, lat: number, pts: Pt[]): boolean => {
  let inside = false;
  for (let i = 0, j = pts.length - 1; i < pts.length; j = i++) {
    const [xi, yi] = pts[i] as Pt;
    const [xj, yj] = pts[j] as Pt;
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
};

// Each polygon is its outer ring plus holes; even-odd inside the polygon, any polygon counts.
const polygons: Pt[][][] = [];
for (const g of topo.objects.land.geometries) {
  // Polygon: rings of arc indices. MultiPolygon: a list of polygons.
  const list = (g.type === 'Polygon' ? [g.arcs] : g.arcs) as number[][][];
  for (const poly of list) polygons.push(poly.map(ring));
}

const ROWS = 90;
const COLS = 180;
const bytes = new Uint8Array(Math.ceil((ROWS * COLS) / 8));
let land = 0;
for (let r = 0; r < ROWS; r++) {
  const lat = 89 - r * 2;
  for (let c = 0; c < COLS; c++) {
    const lon = -179 + c * 2;
    const hit = polygons.some(
      (rings) => rings.reduce((n, pts) => n + Number(inRing(lon, lat, pts)), 0) % 2 === 1,
    );
    if (!hit) continue;
    const bit = r * COLS + c;
    bytes[bit >> 3] = (bytes[bit >> 3] ?? 0) | (1 << (bit & 7));
    land++;
  }
}

writeFileSync(
  'src/lib/land-mask.ts',
  `// Generated by scripts/bake-land.ts from Natural Earth 110 m land (public domain; see content/credits.json). Do not edit.
// 2° grid, ${ROWS} rows (lat 89 → -89) × ${COLS} columns (lon -179 → 179), one bit per cell, row-major, base64. ${land} land cells.
export const LAND_ROWS = ${ROWS};
export const LAND_COLS = ${COLS};
export const LAND_MASK = '${Buffer.from(bytes).toString('base64')}';
`,
);
console.log(
  `bake-land: ${land} land cells of ${ROWS * COLS} (${((100 * land) / (ROWS * COLS)).toFixed(1)}%), ${bytes.length} bytes`,
);
